/**
 * miuzika's canonical data model.
 *
 * It is deliberately independent of the audio engine: this is the "source of
 * truth". openDAW (or any other host) is a view/executor of this model.
 * Musical time in *beats* (quarter notes). PPQN only applies when exporting MIDI.
 */

export type Mode =
  | "major"
  | "minor"
  | "dorian"
  | "phrygian"
  | "lydian"
  | "mixolydian"
  | "harmonicMinor"
  | "pentatonicMinor";

export interface KeySignature {
  /** Tonic note with accidental: "D", "F#", "Bb". */
  tonic: string;
  mode: Mode;
}

type TrackKind = "midi" | "audio";

interface InstrumentSpec {
  type: InstrumentType;
  /** Preset name in the host (e.g. "Vaporisateur"). */
  preset?: string;
  /** GM program for the MIDI export. */
  program?: number;
  /** Instrument file, relative to the project (a .sf2 for `soundfont`). */
  archivo?: string;
}

export const DEVICE_TYPES = [
  "reverb",
  "delay",
  "chorus",
  "distortion",
  "filter",
  "eq",
  "compressor",
  "bitcrusher",
  "gate",
  "width",
] as const;

export type DeviceType = (typeof DEVICE_TYPES)[number];

export const INSTRUMENT_TYPES = [
  "drumkit",
  "bass",
  "synth",
  "pad",
  "lead",
  "arp",
  "soundfont",
  "sampler",
] as const;

export type InstrumentType = (typeof INSTRUMENT_TYPES)[number];

export interface Device {
  id: string;
  type: DeviceType;
  enabled: boolean;
  /** Parameters normalized 0..1 except those indicated in DEVICE_PARAMS. */
  params: Record<string, number>;
}

export interface Note {
  /** MIDI 0..127. */
  pitch: number;
  /** Beats relative to the start of the clip. */
  start: number;
  duration: number;
  /** 1..127. */
  velocity: number;
}

export interface AudioAsset {
  id: string;
  name: string;
  /** Duration in beats at the project tempo. */
  durationBeats: number;
  /**
   * Path of the WAV inside the project folder ("salida/x.wav"). This is what
   * makes the project portable: the bytes live on disk, not in the browser.
   */
  ruta?: string;
}

interface AudioRef {
  assetId: string;
  /** Offset inside the file, in beats. */
  offset: number;
  gainDb: number;
}

export interface Clip {
  id: string;
  name: string;
  /** Absolute beats on the timeline. */
  start: number;
  length: number;
  notes: Note[];
  audio?: AudioRef;
  /** Traceability: which op and section generated it. */
  origin?: { op: string; section?: string; seed?: number };
}

export interface Track {
  id: string;
  name: string;
  kind: TrackKind;
  instrument: InstrumentSpec;
  gainDb: number;
  /** -1 left, 0 center, 1 right. */
  pan: number;
  muted: boolean;
  solo: boolean;
  devices: Device[];
  clips: Clip[];
  /** Sends to buses (post-fader). With no sends, the track goes only to the master. */
  sends?: Send[];
}

/** A track's send to a bus: how much signal it sends, in dB. */
export interface Send {
  busId: string;
  levelDb: number;
}

/**
 * Auxiliary bus (effects return): a reverb or delay shared by several tracks
 * via sends, instead of one reverb per track. It plays through the master. In
 * openDAW it is an AudioBusBox with its "aux"-type AudioUnit.
 */
export interface Bus {
  id: string;
  name: string;
  gainDb: number;
  devices: Device[];
}

export interface CodeSource {
  id: string;
  name: string;
  language: "strudel";
  code: string;
  /** Bars queried from the pattern. 1 Strudel cycle = 1 bar. */
  bars: number;
  /** Tracks generated by the last compilation. */
  trackIds: string[];
  compiledAt: string;
  /** Editable MIDI or audio rendered with the real Strudel engine. */
  mode?: "midi" | "audio";
  /** WAV asset when mode is audio. */
  assetId?: string;
}

export interface Project {
  schemaVersion: 1;
  id: string;
  name: string;
  bpm: number;
  key: KeySignature;
  timeSignature: { numerator: number; denominator: number };
  lengthBars: number;
  /** Global seed: makes generations reproducible. */
  seed: number;
  tracks: Track[];
  /** Metadata for imported WAVs (the bytes live outside the project). */
  audioAssets?: AudioAsset[];
  /** Code sources that generated tracks; the notes live in tracks. */
  codeSources?: CodeSource[];
  /** Auxiliary buses; tracks send them signal with `sends`. */
  buses?: Bus[];
  master: { gainDb: number };
  meta: {
    /**
     * The project folder in `workspace/proyectos/`. It is fixed when the project is
     * created and does NOT change when it is renamed: the folder used to come from
     * the name on every save, so renaming a project moved it to another folder
     * without its WAVs.
     */
    carpeta?: string;
    prompt?: string;
    generator?: string;
    createdAt: string;
  };
}

